#include "libft.h"

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	s;
	char	*sr;

	sr = (char *)src;
	i = 0;
	s = ft_strlen(sr);
	if (size == 0)
		return (s);
	while (src[i] && i < size - 1)
	{
		dst[i] = src[i];
		i++;
	}
	dst[i] = '\0';
	return (s);
}
