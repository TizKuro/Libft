#include "libft.h"

char	*ft_strdup(const char *src)
{
	size_t	i;
	size_t	srclen;
	char	*new;
	char	*sr;

	sr = (char *)src;
	i = 0;
	srclen = ft_strlen(sr);
	new = malloc(sizeof(char) * (srclen + 1));
	if (!new)
		return (0);
	while (src[i])
	{
		new[i] = src[i];
		i++;
	}
	new[i] = '\0';
	return (new);
}
